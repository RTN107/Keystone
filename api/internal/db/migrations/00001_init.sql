CREATE EXTENSION IF NOT EXISTS vector;

-- Teams are created at startup from KEYSTONE_TEAMS, so this migration holds none.
-- number_prefix drives employee numbers such as DEL-001.
CREATE TABLE teams (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text NOT NULL UNIQUE,
    number_prefix text NOT NULL UNIQUE CHECK (number_prefix ~ '^[A-Z]{2,4}$')
);

-- An admin belongs to no team and cannot use Ask. An employee must belong to one.
CREATE TABLE employees (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_number text NOT NULL UNIQUE CHECK (employee_number ~ '^[A-Z]{2,4}-[0-9]{3,6}$'),
    name            text NOT NULL CHECK (length(btrim(name)) > 0),
    team_id         bigint REFERENCES teams (id),
    role            text NOT NULL CHECK (role IN ('admin', 'employee')),
    password_hash   text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT admin_has_no_team CHECK ((role = 'admin') = (team_id IS NULL))
);

-- content is the normalized extracted text. Chunk offsets index into it, so the
-- document viewer can highlight a cited passage.
CREATE TABLE documents (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    title           text NOT NULL CHECK (length(btrim(title)) > 0),
    source_filename text NOT NULL,
    content         text NOT NULL,
    ingested_by     bigint REFERENCES employees (id),
    created_at      timestamptz NOT NULL DEFAULT now()
);

-- The only place access lives. granted_at, granted_by and source keep the tags a
-- document was ingested with apart from later extensions.
CREATE TABLE document_access (
    document_id bigint NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    team_id     bigint NOT NULL REFERENCES teams (id),
    granted_at  timestamptz NOT NULL DEFAULT now(),
    granted_by  bigint REFERENCES employees (id),
    source      text NOT NULL CHECK (source IN ('ingest', 'extension')),
    PRIMARY KEY (document_id, team_id)
);
CREATE INDEX document_access_team_idx ON document_access (team_id, document_id);

-- team_id is denormalized on purpose, so the logs screen filters without a join.
CREATE TABLE query_logs (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id     bigint NOT NULL REFERENCES employees (id),
    team_id         bigint NOT NULL REFERENCES teams (id),
    question        text NOT NULL,
    outcome         text NOT NULL CHECK (outcome IN ('answered', 'blocked', 'no_match')),
    was_answered    boolean GENERATED ALWAYS AS (outcome = 'answered') STORED,
    answer_text     text,
    cited_chunk_ids bigint[] NOT NULL DEFAULT '{}',
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX query_logs_team_idx     ON query_logs (team_id, created_at DESC);
CREATE INDEX query_logs_employee_idx ON query_logs (employee_id, created_at DESC);
CREATE INDEX query_logs_created_idx  ON query_logs (created_at DESC);

